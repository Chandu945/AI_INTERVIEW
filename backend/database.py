"""The app's database: PostgreSQL when DATABASE_URL is set (a hosted one, such as Supabase), and
SQLite otherwise (a file on this computer: for running locally, and for the tests).

The app writes its SQL once, with ? for each value, in the SQL both understand, and uses it in
`with connect() as db:` blocks that work the way Python's sqlite3 module does: reads run on their
own, and the first write starts a transaction, saved at the end of the block or undone if the
block fails.

Each statement to a PostgreSQL server far away is a wait (about 60 ms there and back from India to
Supabase's Mumbai region). So connections are kept open in a pool, a read is one trip (with no
BEGIN and COMMIT around it), and results come back in binary, as text would double an image.
"""

import sqlite3
import time
from contextlib import ExitStack, contextmanager
from datetime import timezone
from pathlib import Path
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

SQLITE_TABLES = (
    "CREATE TABLE IF NOT EXISTS sessions (id TEXT PRIMARY KEY, title TEXT NOT NULL DEFAULT 'New Interview',"
    " resume_name TEXT, resume_text TEXT, mode TEXT NOT NULL DEFAULT 'balanced',"
    " created_at TEXT DEFAULT CURRENT_TIMESTAMP, updated_at TEXT DEFAULT CURRENT_TIMESTAMP)",
    "CREATE TABLE IF NOT EXISTS messages (id INTEGER PRIMARY KEY AUTOINCREMENT, conversation_id TEXT NOT NULL,"
    " role TEXT NOT NULL, content TEXT NOT NULL, created_at TEXT DEFAULT CURRENT_TIMESTAMP)",
    "CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages(conversation_id, id)",
    "CREATE TABLE IF NOT EXISTS images (id TEXT PRIMARY KEY, conversation_id TEXT NOT NULL,"
    " mime_type TEXT NOT NULL, data BLOB NOT NULL, created_at TEXT DEFAULT CURRENT_TIMESTAMP)",
    "CREATE INDEX IF NOT EXISTS idx_images_conversation ON images(conversation_id)",
)
# Columns added since the first version, for an older chat.db.
SQLITE_ADDED_COLUMNS = (
    ("sessions", "target_role TEXT NOT NULL DEFAULT 'GenAI Developer'"),
    ("sessions", "interview_type TEXT NOT NULL DEFAULT 'Technical'"),
    ("sessions", "instructions TEXT NOT NULL DEFAULT ''"),
    ("sessions", "job_description TEXT NOT NULL DEFAULT ''"),
    ("messages", "images TEXT NOT NULL DEFAULT ''"),  # the ids of a question's images, comma separated
)

POSTGRES_TABLES = (
    """CREATE TABLE IF NOT EXISTS sessions (
        id TEXT PRIMARY KEY,
        title TEXT NOT NULL DEFAULT 'New Interview',
        resume_name TEXT,
        resume_text TEXT,
        mode TEXT NOT NULL DEFAULT 'balanced',
        target_role TEXT NOT NULL DEFAULT 'GenAI Developer',
        interview_type TEXT NOT NULL DEFAULT 'Technical',
        instructions TEXT NOT NULL DEFAULT '',
        job_description TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now())""",
    """CREATE TABLE IF NOT EXISTS messages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        conversation_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
        role TEXT NOT NULL,
        content TEXT NOT NULL,
        images TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMPTZ NOT NULL DEFAULT now())""",
    "CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages(conversation_id, id)",
    """CREATE TABLE IF NOT EXISTS images (
        id TEXT PRIMARY KEY,
        conversation_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
        mime_type TEXT NOT NULL,
        data BYTEA NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now())""",
    "CREATE INDEX IF NOT EXISTS idx_images_conversation ON images(conversation_id)",
    "CREATE INDEX IF NOT EXISTS idx_sessions_updated ON sessions(updated_at DESC)",
    # Supabase lets anyone with a project's public key use the tables in its public schema through
    # its web API, unless row level security is on. With it on and no rules, that API gets nothing.
    # The app connects as the tables' owner, which the rules don't apply to.
    "ALTER TABLE sessions ENABLE ROW LEVEL SECURITY",
    "ALTER TABLE messages ENABLE ROW LEVEL SECURITY",
    "ALTER TABLE images ENABLE ROW LEVEL SECURITY",
)

# Settings for other tools that a database URL may carry (Supabase's ends "?pgbouncer=true", for
# Prisma), which PostgreSQL's own client turns down.
OTHER_TOOLS_SETTINGS = ("pgbouncer", "connection_limit", "pool_timeout", "statement_cache_size", "schema")
WRITES = ("INSERT", "UPDATE", "DELETE")
# A connection unused for this long is tried before it's used, in case it dropped meanwhile (the
# computer slept, say), so a question doesn't fail on it.
IDLE_CHECK_SECONDS = 60


class DatabaseUnavailable(Exception):
    """The database couldn't be reached, or the connection to it broke."""


def is_postgres(url: str) -> bool:
    return url.startswith(("postgres://", "postgresql://"))


def client_url(url: str) -> str:
    """The URL without other tools' settings."""
    parts = urlsplit(url)
    if not parts.query:
        return url
    kept = [(k, v) for k, v in parse_qsl(parts.query, keep_blank_values=True) if k not in OTHER_TOOLS_SETTINGS]
    return urlunsplit(parts._replace(query=urlencode(kept)))


def read_times_as_sqlite_does(connection):
    """Has the connection read times the way SQLite writes them ("2026-11-07 08:16:22", in UTC),
    so the app sends the same with either database."""
    from psycopg.types.datetime import TimestamptzBinaryLoader, TimestamptzLoader

    for base in (TimestamptzLoader, TimestamptzBinaryLoader):

        class Loader(base):
            def load(self, data):
                return super().load(data).astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")

        connection.adapters.register_loader("timestamptz", Loader)


def postgres_execute(connection, sql: str, params=()):
    """Runs the app's SQL, with ? for each value, on a psycopg connection. SQL without values goes as
    it is (as text): it may hold several statements."""
    return connection.execute(sql.replace("?", "%s"), params or None, binary=bool(params))


class PostgresConnection:
    """A pooled PostgreSQL connection that takes the app's SQL, with ? for each value."""

    def __init__(self, connection, transactions: ExitStack, schema: str):
        self.connection = connection
        self.transactions = transactions
        self.in_transaction = False
        if schema:
            # The whole block in one transaction that starts by saying where the tables are. With a
            # transaction pooler (Supabase's, on port 6543), a setting made outside a transaction
            # may not hold for the next statement, which would then reach the tables in public.
            self.begin()
            connection.execute(f'SET LOCAL search_path TO "{schema}"')

    def begin(self):
        if not self.in_transaction:
            self.transactions.enter_context(self.connection.transaction())
            self.in_transaction = True

    def execute(self, sql: str, params=()):
        if sql.lstrip()[:6].upper() in WRITES:
            self.begin()
        return postgres_execute(self.connection, sql, params)

    def executemany(self, sql: str, rows):
        self.begin()
        with self.connection.cursor() as cursor:
            cursor.executemany(sql.replace("?", "%s"), rows)


class Database:
    """Where interviews are kept. `schema` (PostgreSQL only) keeps the tables apart from those in
    public: the tests use their own."""

    def __init__(self, url: str = "", path: Path | None = None, schema: str = ""):
        self.postgres = is_postgres(url)
        self.url = client_url(url) if self.postgres else url
        self.path = path
        self.schema = schema
        self.pool = None
        self.unavailable: tuple = ()  # the errors that mean the database is out of reach

    @property
    def kind(self) -> str:
        return "PostgreSQL" if self.postgres else "SQLite"

    def open(self):
        """Connects, and makes the tables if they aren't there yet."""
        if self.postgres:
            self._open_pool()
            if self.schema:
                with self.pool.connection() as connection:
                    connection.execute(f'CREATE SCHEMA IF NOT EXISTS "{self.schema}"')
            with self.connect() as db:
                db.execute(";\n".join(POSTGRES_TABLES))  # all in one trip
            return
        with self.connect() as db:
            for statement in SQLITE_TABLES:
                db.execute(statement)
            for table, column in SQLITE_ADDED_COLUMNS:
                try:
                    db.execute(f"ALTER TABLE {table} ADD COLUMN {column}")
                except sqlite3.OperationalError:
                    pass  # it's there already

    def _open_pool(self):
        import psycopg
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool, PoolTimeout

        self.unavailable = (psycopg.OperationalError, psycopg.InterfaceError)

        def configure(connection):
            read_times_as_sqlite_does(connection)
            connection.last_used = time.monotonic()

        def check(connection):
            if time.monotonic() - connection.last_used > IDLE_CHECK_SECONDS:
                ConnectionPool.check_connection(connection)

        self.pool = ConnectionPool(
            self.url,
            # A question reads its interview's settings, messages and images at the same time.
            min_size=3,
            max_size=8,
            timeout=15,
            configure=configure,
            check=check,
            kwargs={
                "autocommit": True,  # reads run on their own; PostgresConnection starts transactions
                "row_factory": dict_row,
                "prepare_threshold": None,  # no prepared statements: a transaction pooler can't keep them
                "connect_timeout": 10,
                # Keeps idle connections open through home routers, and notices any that drop.
                "keepalives": 1,
                "keepalives_idle": 30,
                "keepalives_interval": 10,
                "keepalives_count": 3,
            },
            name="interviews",
            open=True,
        )
        try:
            self.pool.wait(timeout=20)
        except PoolTimeout:
            self.close()
            # The pool only says it timed out: connecting once says why (a wrong password, say).
            psycopg.connect(self.url, connect_timeout=10).close()
            raise

    def close(self):
        if self.pool is not None:
            self.pool.close()
            self.pool = None

    @contextmanager
    def connect(self):
        """A connection: reads run on their own, and the first write starts a transaction, saved at
        the end of the block or undone if the block fails."""
        if self.postgres:
            try:
                with self.pool.connection() as connection, ExitStack() as transactions:
                    connection.last_used = time.monotonic()
                    yield PostgresConnection(connection, transactions, self.schema)
            except self.unavailable as exc:
                raise DatabaseUnavailable(str(exc)) from exc
            return
        connection = sqlite3.connect(self.path)
        connection.row_factory = sqlite3.Row
        try:
            with connection:
                yield connection
        finally:
            connection.close()

    def run(self, sql: str, params=()):
        """One statement on its own, saved at once; returns it, for its rowcount. With PostgreSQL
        that's one trip: a single statement is all or nothing anyway, so it needs no BEGIN and
        COMMIT around it."""
        if self.postgres and not self.schema:
            try:
                with self.pool.connection() as connection:
                    connection.last_used = time.monotonic()
                    return postgres_execute(connection, sql, params)
            except self.unavailable as exc:
                raise DatabaseUnavailable(str(exc)) from exc
        with self.connect() as db:
            return db.execute(sql, params)

    def drop_schema(self):
        """For the tests: removes their schema, and everything in it."""
        if self.postgres and self.schema:
            import psycopg

            with psycopg.connect(self.url, autocommit=True, prepare_threshold=None) as connection:
                connection.execute(f'DROP SCHEMA IF EXISTS "{self.schema}" CASCADE')

    def empty(self):
        """For the tests: deletes every interview, so each test starts from nothing. With PostgreSQL,
        only in a schema of their own, so the interviews in public are never touched."""
        if self.postgres and not self.schema:
            raise RuntimeError("empty() only empties a schema of the tests' own")
        with self.connect() as db:
            if self.postgres and db.execute("SELECT current_schema() AS name").fetchone()["name"] != self.schema:
                raise RuntimeError(f"Not emptying: the tables aren't in {self.schema}")
            for table in ("images", "messages", "sessions"):
                db.execute(f"DELETE FROM {table}")
